// v45: mapping between a TeachyRooms lesson and a Google Calendar event (pure, unit-tested; no secrets here).

/** Stable Google event id for a lesson: base32hex-safe ("tr" + the lesson uuid without dashes). Same lesson → same
 *  event id, so a repeated or concurrent create can never produce a second event. */
export const eventIdFor = (lessonId: string) => 'tr' + lessonId.toLowerCase().replace(/[^0-9a-f]/g, '');
export const isEventIdOfLesson = (id: string) => /^tr[0-9a-f]{32}$/.test(id);

export type OutboxRow = {
  id: number; op: 'upsert' | 'delete'; lesson_id: string; event_id: string | null;
  starts_at: string | null; ends_at: string | null; timezone: string | null; status: string | null; language: string | null;
  title: string | null; description: string | null; student_id: string | null; student_name: string | null; student_email: string | null;
  curriculum_subject?: string | null; lesson_language?: string | null; subject?: string | null;
};

const LANG: Record<string, string> = {nl: 'Nederlands', pt: 'Portugees', en: 'Engels', es: 'Spaans', fr: 'Frans', de: 'Duits'};
export const lessonLang = (r: Pick<OutboxRow, 'language' | 'curriculum_subject' | 'lesson_language'>) =>
  [r.language, r.curriculum_subject, r.lesson_language].find(x => !!x && /^[a-z]{2}$/.test(x)) || null;

export function defaultSummary(r: OutboxRow) {
  const l = lessonLang(r);
  return (l ? `Les ${LANG[l] || l.toUpperCase()}` : 'Les') + ` · ${r.student_name || 'leerling'}`;
}
export function defaultDescription(r: OutboxRow, origin: string) {
  return `TeachyRooms-les met ${r.student_name || 'je leerling'}.\nKlaslokaal: ${origin}/klaslokaal/live?student=${encodeURIComponent(r.student_id || '')}&lesson=${encodeURIComponent(r.lesson_id)}`;
}
/** Short fingerprint (no crypto needed): lets the pull side recognise "this is still our default text". */
export function fp(s: string) { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0; return (h >>> 0).toString(36); }

/** Google event body for a lesson. Attendees are only set when the teacher chose to invite students. */
export function eventBody(r: OutboxRow, o: {origin: string; attendees?: {email: string; responseStatus?: string}[] | null}) {
  const summary = r.title || defaultSummary(r), description = r.description || defaultDescription(r, o.origin);
  const tz = r.timezone || 'Europe/Amsterdam';
  return {
    summary, description, status: 'confirmed',
    start: {dateTime: new Date(r.starts_at!).toISOString(), timeZone: tz},
    end: {dateTime: new Date(r.ends_at!).toISOString(), timeZone: tz},
    extendedProperties: {private: {teachy: '1', teachyLessonId: r.lesson_id, teachyStudentId: r.student_id || '', teachyLang: lessonLang(r) || '',
      teachySum: r.title ? '' : fp(summary), teachyDesc: r.description ? '' : fp(description)}},
    guestsCanModify: false, guestsCanInviteOthers: false,
    ...(o.attendees ? {attendees: o.attendees} : {}),
  };
}

/** Existing guests + the student once (no double invitation; other guests the teacher added stay). */
export function mergeAttendees(existing: {email?: string}[] | undefined, studentEmail: string | null) {
  const list = (existing || []).filter(a => a.email) as {email: string}[];
  if (studentEmail && !list.some(a => a.email.toLowerCase() === studentEmail.toLowerCase())) list.push({email: studentEmail});
  return list;
}

export type GEvent = {id: string; status?: string; updated?: string; summary?: string; description?: string;
  start?: {dateTime?: string; date?: string; timeZone?: string}; end?: {dateTime?: string; date?: string; timeZone?: string};
  extendedProperties?: {private?: Record<string, string>}; recurringEventId?: string};

/** Google → what the database applies. Default texts (generated by TeachyRooms) are not taken over as a title. */
export function toApply(e: GEvent) {
  const p = e.extendedProperties?.private || {};
  const out: Record<string, unknown> = {id: e.id, status: e.status || 'confirmed', updated: e.updated || null};
  if (e.status === 'cancelled') return out;
  if (e.start?.date || e.end?.date) { out.all_day = true; return out; }
  out.start = e.start?.dateTime || null; out.end = e.end?.dateTime || null; out.tz = e.start?.timeZone || null;
  if (typeof e.summary === 'string' && !(p.teachySum && fp(e.summary) === p.teachySum)) out.summary = e.summary;
  if (typeof e.description === 'string' && !(p.teachyDesc && fp(e.description) === p.teachyDesc)) out.description = e.description;
  return out;
}
/** Only TeachyRooms events (or deletions, which Google sends without details) go to the database. */
export const relevant = (e: GEvent) => isEventIdOfLesson(e.id) || !!e.extendedProperties?.private?.teachyLessonId || e.status === 'cancelled';
